"""Assemble the external benchmark corpus from three real sources.

1. SecurityEval (Siddiq & Santos, MSR 2022, DOI 10.1145/3549035.3561184):
   Python generated by GitHub Copilot for security-sensitive prompts.
   Labeled ``defective`` per the dataset's construction; label noise is
   acknowledged in docs/benchmark.md.
2. LLM solutions generated for tasks/ (see generate_corpus.py). Labeled by
   executing the task's reference tests: pass -> ``clean``, fail -> ``defective``.
3. Clean open-source files pinned to release tags (corpus/clean_oss/,
   provenance in sources.json). Labeled ``clean`` - the false positive probe.
4. Injected defects: clean LLM solutions from (2) with one known defect class
   injected deterministically (inject_defects.py, seed in provenance). This is
   the only synthetic slice; it covers the generated-code defect profile
   (hallucinated imports/kwargs, stubs, placeholders) that (1) does not.

Every sample keeps full provenance so any label can be audited.
"""
import argparse
import ast
import json
import random
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from inject_defects import INJECTIONS  # noqa: E402  # trustgate: ignore TG-D01

HERE = Path(__file__).parent
RAW = HERE / "raw"
TASKS = HERE / "tasks"
CLEAN_OSS = HERE / "corpus" / "clean_oss"


def securityeval_samples(dataset_root: Path) -> list[dict]:
    samples = []
    testcases = dataset_root / "Testcases_Copilot"
    if not testcases.is_dir():
        sys.exit(f"not a SecurityEval checkout: {dataset_root}")
    for path in sorted(testcases.rglob("*.py")):
        code = path.read_text(encoding="utf-8", errors="replace")
        try:
            ast.parse(code)
        except SyntaxError:
            continue  # comparing parseable code keeps all tools on equal footing
        cwe = path.parent.name
        samples.append({
            "id": f"seceval_copilot_{cwe}_{path.stem}",
            "label": "defective",
            "code": code,
            "source": {
                "dataset": "SecurityEval",
                "generator": "github-copilot",
                "cwe": cwe,
                "file": str(path.relative_to(dataset_root)),
                "citation": "Siddiq & Santos, MSR 2022, DOI 10.1145/3549035.3561184",
            },
        })
    return samples


def _run_reference_tests(code: str, tests_path: Path, timeout: int = 60) -> tuple[bool, str]:
    """Execute reference tests against a generated solution in a throwaway dir."""
    with tempfile.TemporaryDirectory(prefix="trustgate-label-") as tmp:
        tmp_path = Path(tmp)
        (tmp_path / "solution.py").write_text(code, encoding="utf-8")
        shutil.copy(tests_path, tmp_path / "test_reference.py")
        try:
            proc = subprocess.run(
                [sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider"],
                cwd=tmp_path, capture_output=True, text=True, timeout=timeout,
            )
        except subprocess.TimeoutExpired:
            return False, "timeout"
        return proc.returncode == 0, (proc.stdout + proc.stderr)[-400:]


def llm_samples() -> list[dict]:
    samples = []
    if not RAW.is_dir():
        return samples
    for model_dir in sorted(p for p in RAW.iterdir() if p.is_dir()):
        for raw_file in sorted(model_dir.glob("*.json")):
            data = json.loads(raw_file.read_text(encoding="utf-8"))
            task = data["task"]
            code = data["code"]
            try:
                ast.parse(code)
            except SyntaxError:
                passed, detail = False, "syntax error"
            else:
                tests_path = TASKS / task / "reference_tests.py"
                passed, detail = _run_reference_tests(code, tests_path)
            samples.append({
                "id": f"llm_{model_dir.name}_{task}",
                "label": "clean" if passed else "defective",
                "code": code,
                "source": {
                    "dataset": "trustgate-tasks",
                    "generator": data.get("model", model_dir.name),
                    "task": task,
                    "labeled_by": "reference tests",
                    "test_result": "pass" if passed else f"fail: {detail}",
                },
            })
    return samples


def injected_samples(llm: list[dict], seed: int = 42) -> list[dict]:
    """One known defect class injected into each clean LLM solution."""
    rng = random.Random(seed)
    clean = [item for item in llm if item["label"] == "clean"]
    samples = []
    for index, item in enumerate(clean):
        inject = INJECTIONS[index % len(INJECTIONS)]
        result = inject(item["code"], rng)
        if result is None:
            continue
        mutated, defect = result
        samples.append({
            "id": f"inj_{inject.__name__.removeprefix('inject_')}_{item['id']}",
            "label": "defective",
            "code": mutated,
            "source": {
                "dataset": "injected-defects",
                "base_sample": item["id"],
                "defect_class": defect,
                "injector": inject.__name__,
                "seed": seed,
            },
        })
    return samples


def clean_oss_samples() -> list[dict]:
    samples = []
    sources = json.loads((CLEAN_OSS / "sources.json").read_text(encoding="utf-8"))
    by_file = {item["file"]: item for item in sources}
    # stored as .py.example so `trustgate scan .` never treats corpus data
    # as the project's own code (same convention as examples/)
    for path in sorted(CLEAN_OSS.glob("*.py.example")):
        meta = by_file[path.name.removesuffix(".example")]
        samples.append({
            "id": f"oss_{path.name.removesuffix('.py.example')}",
            "label": "clean",
            "code": path.read_text(encoding="utf-8"),
            "source": {
                "dataset": "clean-oss",
                "repo": meta["repo"],
                "ref": meta["ref"],
                "path": meta["path"],
                "license": meta["license"],
            },
        })
    return samples


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Build the TrustGate benchmark corpus")
    parser.add_argument("--securityeval", required=True,
                        help="path to a github.com/s2e-lab/SecurityEval checkout")
    parser.add_argument("--out", default=str(HERE / "corpus" / "corpus.json"))
    args = parser.parse_args(argv)

    llm = llm_samples()
    corpus = (
        securityeval_samples(Path(args.securityeval))
        + llm
        + injected_samples(llm)
        + clean_oss_samples()
    )
    by_label = {}
    by_dataset = {}
    for item in corpus:
        by_label[item["label"]] = by_label.get(item["label"], 0) + 1
        ds = item["source"]["dataset"]
        by_dataset[ds] = by_dataset.get(ds, 0) + 1

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(corpus, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(corpus)} samples -> {out}")
    print("labels:", by_label)
    print("datasets:", by_dataset)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
